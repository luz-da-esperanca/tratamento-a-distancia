-- ==========================================
-- 2.1. CRIAR TIPOS ENUM
-- ==========================================

CREATE TYPE status_agendamento AS ENUM ('AGENDADO', 'FINALIZADO');
CREATE TYPE opcao_whatsapp AS ENUM ('E_WHATSAPP', 'OUTRO_NUMERO', 'NAO_TEM');
CREATE TYPE tipo_email AS ENUM ('PROGRAMADO', 'PONTUAL');

-- Enum adicional para atuar como "Discriminador" da herança da classe Agendamento
CREATE TYPE tipo_tratamento AS ENUM ('TRATAMENTO_SEM_CIRURGIA', 'TRATAMENTO_COM_CIRURGIA');


-- ==========================================
-- 2.2. TABELA PACIENTES
-- ==========================================

CREATE TABLE pacientes (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    nome_completo VARCHAR NOT NULL,
    data_nascimento DATE NOT NULL,
    pais VARCHAR NOT NULL,
    estado VARCHAR NOT NULL,
    cidade VARCHAR NOT NULL,
    endereco TEXT NOT NULL
);


-- ==========================================
-- 2.3. TABELA AGENDAMENTOS (Com Herança)
-- ==========================================

CREATE TABLE agendamentos (
    protocolo VARCHAR PRIMARY KEY, -- Definido como PK no diagrama
    paciente_id UUID NOT NULL REFERENCES pacientes(id) ON DELETE CASCADE,
    tipo tipo_tratamento NOT NULL, -- Coluna que define a subclasse (Com ou Sem Cirurgia)
    
    -- Atributos da classe abstrata Agendamento
    data_cadastro TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    status status_agendamento NOT NULL DEFAULT 'AGENDADO',
    email_notificacao VARCHAR NOT NULL,
    celular VARCHAR NOT NULL,
    tipo_whatsapp opcao_whatsapp NOT NULL,
    whatsapp_auxiliar VARCHAR,
    eh_intercessorio BOOLEAN NOT NULL DEFAULT false,
    nome_solicitante VARCHAR NOT NULL,

    enviou_email_terca BOOLEAN DEFAULT false,
    enviou_email_quarta BOOLEAN DEFAULT false,
    
    -- Atributos específicos da subclasse TratamentoComCirurgia
    -- (Permite nulo pois 'TratamentoSemCirurgia' não possuirá este dado)
    data_cirurgia DATE
);


-- ==========================================
-- 2.4. TABELA TEMPLATE_EMAILS
-- ==========================================

CREATE TABLE template_emails (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- Long no diagrama
    assunto VARCHAR NOT NULL,
    corpo TEXT NOT NULL,
    tipo tipo_email NOT NULL
);


-- ==========================================
-- 2.5. CONFIGURAR RLS (ROW LEVEL SECURITY)
-- ==========================================

-- Habilitar a segurança em nível de linha para todas as tabelas
ALTER TABLE pacientes ENABLE ROW LEVEL SECURITY;
ALTER TABLE agendamentos ENABLE ROW LEVEL SECURITY;
ALTER TABLE template_emails ENABLE ROW LEVEL SECURITY;

-- 1. Políticas para o Administrador (Usuários logados no Supabase Auth)
-- Permite controle total (CRUD) em todas as entidades conforme o diagrama
CREATE POLICY "Admin tem controle total sobre pacientes" 
ON pacientes FOR ALL TO authenticated USING (true);

CREATE POLICY "Admin tem controle total sobre agendamentos" 
ON agendamentos FOR ALL TO authenticated USING (true);

CREATE POLICY "Admin tem controle total sobre templates de email" 
ON template_emails FOR ALL TO authenticated USING (true);

-- 2. Políticas para o Paciente (Usuários Anônimos)
-- Conforme a nota: "O acesso do paciente é feito apenas através do 'Protocolo'."
-- Liberamos o SELECT para anônimos, mas a restrição de buscar APENAS pelo protocolo 
-- será garantida na camada da aplicação (Server Actions do Next.js).
CREATE POLICY "Pacientes podem consultar agendamentos via protocolo" 
ON agendamentos FOR SELECT TO anon USING (true);

CREATE POLICY "Pacientes podem consultar seus dados vinculados" 
ON pacientes FOR SELECT TO anon USING (true);

-- NOVAS REGRAS: Permitir que o formulário público do site crie novos registros
-- Permitir que qualquer pessoa (pública/anon) crie um paciente
CREATE POLICY "Permitir insercao publica em pacientes" 
ON pacientes FOR INSERT TO anon WITH CHECK (true);

-- Permitir que qualquer pessoa (pública/anon) crie um agendamento
CREATE POLICY "Permitir insercao publica em agendamentos" 
ON agendamentos FOR INSERT TO anon WITH CHECK (true);